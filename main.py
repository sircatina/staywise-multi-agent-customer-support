from datetime import date
from uuid import uuid4

from langgraph.types import Command

from workflow.graph import build_graph


def print_trace(result: dict) -> None:
    """
    Display the execution trace generated by the workflow.
    """

    print("\nEXECUTION TRACE:")

    trace = result.get("trace", [])

    if not trace:
        print("No trace information available.")
        return

    for event in trace:
        print(f"✓ {event}")


def main():
    """
    Run the StayWise multi-agent customer support workflow.
    """

    # Build the LangGraph workflow
    graph = build_graph()

    print("=" * 60)
    print("StayWise Multi-Agent Customer Support")
    print("=" * 60)

    # Read customer message
    customer_message = input(
        "\nCustomer message: "
    ).strip()

    if not customer_message:
        print("\nPlease enter a customer message.")
        return

    # Each conversation receives its own thread ID.
    # This is required by the LangGraph checkpointer.
    thread_id = str(uuid4())

    config = {
        "configurable": {
            "thread_id": thread_id
        }
    }

    # Initial workflow state
    initial_state = {
        "customer_message": customer_message,
        "request_date": date.today().isoformat(),
        "trace": []
    }

    # Run workflow
    result = graph.invoke(
        initial_state,
        config=config
    )

    # --------------------------------------------------------
    # HUMAN APPROVAL
    # --------------------------------------------------------

    if "__interrupt__" in result:

        interrupt_data = (
            result["__interrupt__"][0].value
        )

        print("\n" + "=" * 60)
        print("HUMAN APPROVAL REQUIRED")
        print("=" * 60)

        print(
            f"Reservation: "
            f"{interrupt_data.get('reservation_id')}"
        )

        print(
            f"Category: "
            f"{interrupt_data.get('category')}"
        )

        print(
            f"Reason: "
            f"{interrupt_data.get('reason')}"
        )

        print(
            f"Refund amount: "
            f"{interrupt_data.get('refund_amount_eur')} EUR"
        )

        # Ask the human operator for a decision
        while True:

            choice = input(
                "\nApprove refund? (yes/no): "
            ).strip().lower()

            if choice in ("yes", "y"):
                approved = True
                break

            if choice in ("no", "n"):
                approved = False
                break

            print(
                "Invalid option. Please enter yes or no."
            )

        # Resume LangGraph from the interrupt
        result = graph.invoke(
            Command(
                resume={
                    "approved": approved
                }
            ),
            config=config
        )

    # --------------------------------------------------------
    # FINAL CUSTOMER RESPONSE
    # --------------------------------------------------------

    print("\n" + "=" * 60)
    print("FINAL RESPONSE")
    print("=" * 60)

    final_response = result.get(
        "final_response",
        "No response was generated."
    )

    print(final_response)

    # --------------------------------------------------------
    # EXECUTION TRACE
    # --------------------------------------------------------

    print_trace(result)

    print("\n" + "=" * 60)


if __name__ == "__main__":
    main()